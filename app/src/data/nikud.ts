/** הסרת ניקוד וסימני טעמים */
export function stripNikud(text: string): string {
  return text.replace(/[\u0591-\u05C7]/g, '');
}

/** האם המחרוזת היא אות בודדת (בלי ניקוד)? */
export function isSingleLetter(text: string): boolean {
  const letters = [...stripNikud(text)].filter((c) => /[א-ת]/.test(c));
  return letters.length <= 1;
}

