/**
 * ניקוד להצגה — כתב דפוס וכתב יד (כשמופעל בהעדפות).
 */
export function withNikud(text: string): string {
  const bare = stripNikud(text).trim();
  if (!bare || isSingleLetter(bare)) return bare;

  // נבדק בזמן קריאה — כיבוי ניקוד מחזיר טקסט נקי
  try {
    if (typeof localStorage !== 'undefined' && localStorage.getItem('agol_show_nikud') === 'off') {
      return bare;
    }
  } catch { /* ignore */ }

  if (NIKUD[bare]) return NIKUD[bare];

  return bare.replace(/[א-ת]+/g, (w) => NIKUD[w] ?? w);
}

/** תצוגה לפי העדפת ניקוד (explicit) */
export function displayText(text: string, enabled = true): string {
  if (!enabled) return stripNikud(text);
  // כשהעדפה דלוקה — תמיד מנקרים (גם אם LS כבוי זמנית בבדיקה)
  const bare = stripNikud(text).trim();
  if (!bare || isSingleLetter(bare)) return bare;
  if (NIKUD[bare]) return NIKUD[bare];
  return bare.replace(/[א-ת]+/g, (w) => NIKUD[w] ?? w);
}

/** תצוגת כתב יד — לפי אותה העדפה */
export function forHandwriting(text: string): string {
  return withNikud(text);
}
